-- 1. Estructura real: tipo, largo y nulabilidad de cada columna.
SELECT c.ORDINAL_POSITION AS orden, c.COLUMN_NAME AS columna, c.DATA_TYPE AS tipo,
       c.CHARACTER_MAXIMUM_LENGTH AS largo, c.NUMERIC_PRECISION AS precision_num,
       c.NUMERIC_SCALE AS escala, c.IS_NULLABLE AS acepta_nulos,
       CASE WHEN c.COLUMN_NAME IN (N'HDESREL', N'HFECPRO', N'HPOSTCOORPDM', N'HPOSTGREG', N'HPOSTJAGRO', N'HPOSTJINCL', N'HPRECOORPDM', N'HPREGREG', N'HPREJAGRO', N'HPREJINCL') THEN 1 ELSE 0 END AS usada_por_reportes
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE c.TABLE_SCHEMA = N'com_act' AND c.TABLE_NAME = N'HMSUP001'
ORDER BY c.ORDINAL_POSITION;

-- 2. Tamaño (sin recorrer la tabla).
SELECT SUM(p.rows) AS filas
FROM sys.partitions p
WHERE p.object_id = OBJECT_ID(N'com_act.HMSUP001') AND p.index_id IN (0, 1);

-- 3. Muestra de las columnas que usan los reportes.
SELECT TOP (100) [HDESREL], [HFECPRO], [HPOSTCOORPDM], [HPOSTGREG], [HPOSTJAGRO], [HPOSTJINCL], [HPRECOORPDM], [HPREGREG], [HPREJAGRO], [HPREJINCL]
FROM [storage].[com_act].[HMSUP001] WITH (NOLOCK);

-- 4. Perfil rápido: nulos y valores distintos por columna usada.
SELECT
    COUNT(*) AS filas,
    SUM(CASE WHEN [HDESREL] IS NULL THEN 1 ELSE 0 END) AS [nulos_HDESREL], COUNT(DISTINCT [HDESREL]) AS [distintos_HDESREL],
    SUM(CASE WHEN [HFECPRO] IS NULL THEN 1 ELSE 0 END) AS [nulos_HFECPRO], COUNT(DISTINCT [HFECPRO]) AS [distintos_HFECPRO],
    SUM(CASE WHEN [HPOSTCOORPDM] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPOSTCOORPDM], COUNT(DISTINCT [HPOSTCOORPDM]) AS [distintos_HPOSTCOORPDM],
    SUM(CASE WHEN [HPOSTGREG] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPOSTGREG], COUNT(DISTINCT [HPOSTGREG]) AS [distintos_HPOSTGREG],
    SUM(CASE WHEN [HPOSTJAGRO] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPOSTJAGRO], COUNT(DISTINCT [HPOSTJAGRO]) AS [distintos_HPOSTJAGRO],
    SUM(CASE WHEN [HPOSTJINCL] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPOSTJINCL], COUNT(DISTINCT [HPOSTJINCL]) AS [distintos_HPOSTJINCL],
    SUM(CASE WHEN [HPRECOORPDM] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPRECOORPDM], COUNT(DISTINCT [HPRECOORPDM]) AS [distintos_HPRECOORPDM],
    SUM(CASE WHEN [HPREGREG] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPREGREG], COUNT(DISTINCT [HPREGREG]) AS [distintos_HPREGREG],
    SUM(CASE WHEN [HPREJAGRO] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPREJAGRO], COUNT(DISTINCT [HPREJAGRO]) AS [distintos_HPREJAGRO],
    SUM(CASE WHEN [HPREJINCL] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPREJINCL], COUNT(DISTINCT [HPREJINCL]) AS [distintos_HPREJINCL]
FROM [storage].[com_act].[HMSUP001] WITH (NOLOCK);
