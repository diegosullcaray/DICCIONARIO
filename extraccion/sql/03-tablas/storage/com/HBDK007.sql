    COUNT(*) AS filas,
    SUM(CASE WHEN [HBFOREXT] IS NULL THEN 1 ELSE 0 END) AS [nulos_HBFOREXT], COUNT(DISTINCT [HBFOREXT]) AS [distintos_HBFOREXT],
