    SUM(CASE WHEN [HBPTOPLUS] IS NULL THEN 1 ELSE 0 END) AS [nulos_HBPTOPLUS], COUNT(DISTINCT [HBPTOPLUS]) AS [distintos_HBPTOPLUS],
    SUM(CASE WHEN [HBRIEOPE] IS NULL THEN 1 ELSE 0 END) AS [nulos_HBRIEOPE], COUNT(DISTINCT [HBRIEOPE]) AS [distintos_HBRIEOPE],
    SUM(CASE WHEN [hcolbt] IS NULL THEN 1 ELSE 0 END) AS [nulos_hcolbt], COUNT(DISTINCT [hcolbt]) AS [distintos_hcolbt],
    SUM(CASE WHEN [HCOLCAR] IS NULL THEN 1 ELSE 0 END) AS [nulos_HCOLCAR], COUNT(DISTINCT [HCOLCAR]) AS [distintos_HCOLCAR],
