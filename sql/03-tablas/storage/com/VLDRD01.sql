-- 1. Estructura real: tipo, largo y nulabilidad de cada columna.
SELECT c.ORDINAL_POSITION AS orden, c.COLUMN_NAME AS columna, c.DATA_TYPE AS tipo,
       c.CHARACTER_MAXIMUM_LENGTH AS largo, c.NUMERIC_PRECISION AS precision_num,
       c.NUMERIC_SCALE AS escala, c.IS_NULLABLE AS acepta_nulos,
       CASE WHEN c.COLUMN_NAME IN (N'HCODOPE', N'HCODSEC', N'HCTACLI', N'HDCLI', N'HDIAATR', N'HDREACC', N'HDSITCRED', N'HFECPRO', N'HFFINVIG', N'HFINIVIG', N'HHORPRO', N'HNUMDOC', N'HPAIS', N'HSALCAPMN', N'HTIPDOC', N'HTIPOPE', N'HTIPSBS') THEN 1 ELSE 0 END AS usada_por_reportes
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE c.TABLE_SCHEMA = N'com' AND c.TABLE_NAME = N'VLDRD01'
ORDER BY c.ORDINAL_POSITION;

-- 2. Tamaño (sin recorrer la tabla).
SELECT SUM(p.rows) AS filas
FROM sys.partitions p
WHERE p.object_id = OBJECT_ID(N'com.VLDRD01') AND p.index_id IN (0, 1);

-- 3. Muestra de las columnas que usan los reportes.
SELECT TOP (100) [HCODOPE], [HCODSEC], [HCTACLI], [HDCLI], [HDIAATR], [HDREACC], [HDSITCRED], [HFECPRO], [HFFINVIG], [HFINIVIG], [HHORPRO], [HNUMDOC], [HPAIS], [HSALCAPMN], [HTIPDOC], [HTIPOPE], [HTIPSBS]
FROM [storage].[com].[VLDRD01] WITH (NOLOCK);

-- 4. Perfil rápido: nulos y valores distintos por columna usada.
