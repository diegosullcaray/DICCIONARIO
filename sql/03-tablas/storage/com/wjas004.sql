    SUM(CASE WHEN [htipcod] IS NULL THEN 1 ELSE 0 END) AS [nulos_htipcod], COUNT(DISTINCT [htipcod]) AS [distintos_htipcod],
    SUM(CASE WHEN [HTIPCRED] IS NULL THEN 1 ELSE 0 END) AS [nulos_HTIPCRED], COUNT(DISTINCT [HTIPCRED]) AS [distintos_HTIPCRED],
    SUM(CASE WHEN [HTIPFALT] IS NULL THEN 1 ELSE 0 END) AS [nulos_HTIPFALT], COUNT(DISTINCT [HTIPFALT]) AS [distintos_HTIPFALT],
    SUM(CASE WHEN [HTIPPASI] IS NULL THEN 1 ELSE 0 END) AS [nulos_HTIPPASI], COUNT(DISTINCT [HTIPPASI]) AS [distintos_HTIPPASI],
