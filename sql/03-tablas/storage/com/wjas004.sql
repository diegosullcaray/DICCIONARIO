-- 1. Estructura real: tipo, largo y nulabilidad de cada columna.
SELECT c.ORDINAL_POSITION AS orden, c.COLUMN_NAME AS columna, c.DATA_TYPE AS tipo,
       c.CHARACTER_MAXIMUM_LENGTH AS largo, c.NUMERIC_PRECISION AS precision_num,
       c.NUMERIC_SCALE AS escala, c.IS_NULLABLE AS acepta_nulos,
       CASE WHEN c.COLUMN_NAME IN (N'hcodrel', N'HDATINPUTRXUSA', N'hfecpro', N'HPERCENTCART', N'HPERCENTENROCLINET', N'HPERCENTPASI', N'HPERCENTUSABILIDAD', N'HTIPAMBO', N'htipcod', N'HTIPCRED', N'HTIPFALT', N'HTIPPASI', N'HTOTALCLIENROL') THEN 1 ELSE 0 END AS usada_por_reportes
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE c.TABLE_SCHEMA = N'com' AND c.TABLE_NAME = N'wjas004'
ORDER BY c.ORDINAL_POSITION;

-- 2. Tamaño (sin recorrer la tabla).
SELECT SUM(p.rows) AS filas
FROM sys.partitions p
WHERE p.object_id = OBJECT_ID(N'com.wjas004') AND p.index_id IN (0, 1);

-- 3. Muestra de las columnas que usan los reportes.
SELECT TOP (100) [hcodrel], [HDATINPUTRXUSA], [hfecpro], [HPERCENTCART], [HPERCENTENROCLINET], [HPERCENTPASI], [HPERCENTUSABILIDAD], [HTIPAMBO], [htipcod], [HTIPCRED], [HTIPFALT], [HTIPPASI], [HTOTALCLIENROL]
FROM [storage].[com].[wjas004] WITH (NOLOCK);

-- 4. Perfil rápido: nulos y valores distintos por columna usada.
SELECT
