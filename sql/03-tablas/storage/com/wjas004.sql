    SUM(CASE WHEN [hfecpro] IS NULL THEN 1 ELSE 0 END) AS [nulos_hfecpro], COUNT(DISTINCT [hfecpro]) AS [distintos_hfecpro],
    SUM(CASE WHEN [HPERCENTCART] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPERCENTCART], COUNT(DISTINCT [HPERCENTCART]) AS [distintos_HPERCENTCART],
    SUM(CASE WHEN [HPERCENTENROCLINET] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPERCENTENROCLINET], COUNT(DISTINCT [HPERCENTENROCLINET]) AS [distintos_HPERCENTENROCLINET],
    SUM(CASE WHEN [HPERCENTPASI] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPERCENTPASI], COUNT(DISTINCT [HPERCENTPASI]) AS [distintos_HPERCENTPASI],
    SUM(CASE WHEN [HPERCENTUSABILIDAD] IS NULL THEN 1 ELSE 0 END) AS [nulos_HPERCENTUSABILIDAD], COUNT(DISTINCT [HPERCENTUSABILIDAD]) AS [distintos_HPERCENTUSABILIDAD],
