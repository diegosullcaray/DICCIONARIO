-- 1. Estructura real: tipo, largo y nulabilidad de cada columna.
SELECT c.ORDINAL_POSITION AS orden, c.COLUMN_NAME AS columna, c.DATA_TYPE AS tipo,
       c.CHARACTER_MAXIMUM_LENGTH AS largo, c.NUMERIC_PRECISION AS precision_num,
       c.NUMERIC_SCALE AS escala, c.IS_NULLABLE AS acepta_nulos,
       CASE WHEN c.COLUMN_NAME IN (N'HCODREL', N'HRODAM', N'HSALNOVIG', N'HSALVIGEN', N'HTIPCOD', N'TMMHSALNOVIG', N'TMMRODAMIENTO', N'TMMSALVIGE') THEN 1 ELSE 0 END AS usada_por_reportes
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE c.TABLE_SCHEMA = N'com_act' AND c.TABLE_NAME = N'WRODASAL001'
ORDER BY c.ORDINAL_POSITION;

-- 2. Tamaño (sin recorrer la tabla).
SELECT SUM(p.rows) AS filas
FROM sys.partitions p
WHERE p.object_id = OBJECT_ID(N'com_act.WRODASAL001') AND p.index_id IN (0, 1);

-- 3. Muestra de las columnas que usan los reportes.
SELECT TOP (100) [HCODREL], [HRODAM], [HSALNOVIG], [HSALVIGEN], [HTIPCOD], [TMMHSALNOVIG], [TMMRODAMIENTO], [TMMSALVIGE]
FROM [storage].[com_act].[WRODASAL001] WITH (NOLOCK);

-- 4. Perfil rápido: nulos y valores distintos por columna usada.
SELECT
    COUNT(*) AS filas,
    SUM(CASE WHEN [HCODREL] IS NULL THEN 1 ELSE 0 END) AS [nulos_HCODREL], COUNT(DISTINCT [HCODREL]) AS [distintos_HCODREL],
    SUM(CASE WHEN [HRODAM] IS NULL THEN 1 ELSE 0 END) AS [nulos_HRODAM], COUNT(DISTINCT [HRODAM]) AS [distintos_HRODAM],
    SUM(CASE WHEN [HSALNOVIG] IS NULL THEN 1 ELSE 0 END) AS [nulos_HSALNOVIG], COUNT(DISTINCT [HSALNOVIG]) AS [distintos_HSALNOVIG],
    SUM(CASE WHEN [HSALVIGEN] IS NULL THEN 1 ELSE 0 END) AS [nulos_HSALVIGEN], COUNT(DISTINCT [HSALVIGEN]) AS [distintos_HSALVIGEN],
    SUM(CASE WHEN [HTIPCOD] IS NULL THEN 1 ELSE 0 END) AS [nulos_HTIPCOD], COUNT(DISTINCT [HTIPCOD]) AS [distintos_HTIPCOD],
    SUM(CASE WHEN [TMMHSALNOVIG] IS NULL THEN 1 ELSE 0 END) AS [nulos_TMMHSALNOVIG], COUNT(DISTINCT [TMMHSALNOVIG]) AS [distintos_TMMHSALNOVIG],
    SUM(CASE WHEN [TMMRODAMIENTO] IS NULL THEN 1 ELSE 0 END) AS [nulos_TMMRODAMIENTO], COUNT(DISTINCT [TMMRODAMIENTO]) AS [distintos_TMMRODAMIENTO],
    SUM(CASE WHEN [TMMSALVIGE] IS NULL THEN 1 ELSE 0 END) AS [nulos_TMMSALVIGE], COUNT(DISTINCT [TMMSALVIGE]) AS [distintos_TMMSALVIGE]
FROM [storage].[com_act].[WRODASAL001] WITH (NOLOCK);
