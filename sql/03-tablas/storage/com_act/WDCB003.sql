-- 1. Estructura real: tipo, largo y nulabilidad de cada columna.
SELECT c.ORDINAL_POSITION AS orden, c.COLUMN_NAME AS columna, c.DATA_TYPE AS tipo,
       c.CHARACTER_MAXIMUM_LENGTH AS largo, c.NUMERIC_PRECISION AS precision_num,
       c.NUMERIC_SCALE AS escala, c.IS_NULLABLE AS acepta_nulos,
       CASE WHEN c.COLUMN_NAME IN (N'HCODREL', N'HCOM_10_20K', N'HCOM_3_5K', N'HCOM_3K', N'HCOM_5_10K', N'HCOM_M20K', N'HDESEMB_COM', N'HFECPRO', N'HNUM_COMITE', N'HOPE_APROB', N'HTIPCOD') THEN 1 ELSE 0 END AS usada_por_reportes
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE c.TABLE_SCHEMA = N'com_act' AND c.TABLE_NAME = N'WDCB003'
ORDER BY c.ORDINAL_POSITION;

-- 2. Tamaño (sin recorrer la tabla).
SELECT SUM(p.rows) AS filas
FROM sys.partitions p
WHERE p.object_id = OBJECT_ID(N'com_act.WDCB003') AND p.index_id IN (0, 1);

-- 3. Muestra de las columnas que usan los reportes.
SELECT TOP (100) [HCODREL], [HCOM_10_20K], [HCOM_3_5K], [HCOM_3K], [HCOM_5_10K], [HCOM_M20K], [HDESEMB_COM], [HFECPRO], [HNUM_COMITE], [HOPE_APROB], [HTIPCOD]
FROM [storage].[com_act].[WDCB003] WITH (NOLOCK);

-- 4. Perfil rápido: nulos y valores distintos por columna usada.
