    SUM(CASE WHEN [HCOM_3K] IS NULL THEN 1 ELSE 0 END) AS [nulos_HCOM_3K], COUNT(DISTINCT [HCOM_3K]) AS [distintos_HCOM_3K],
    SUM(CASE WHEN [HCOM_5_10K] IS NULL THEN 1 ELSE 0 END) AS [nulos_HCOM_5_10K], COUNT(DISTINCT [HCOM_5_10K]) AS [distintos_HCOM_5_10K],
    SUM(CASE WHEN [HCOM_M20K] IS NULL THEN 1 ELSE 0 END) AS [nulos_HCOM_M20K], COUNT(DISTINCT [HCOM_M20K]) AS [distintos_HCOM_M20K],
